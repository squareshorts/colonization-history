"""Analyze lag ratios entirely within the repository-derived area-occupancy estimator.

Individual Tr14/Tr37 records have one biological run each. Fractions are purely
descriptive cross-record comparisons, not a replicated decay curve or confidence
interval. `counts.csv` was generated by `empirical/extract.py` from Figshare's
binary image stacks; the present script needs the released derived lag table.
"""
import csv,json
from pathlib import Path
import numpy as np
from scipy.stats import t
ROOT=Path(__file__).resolve().parents[1]

def run():
    rows=list(csv.DictReader((ROOT/'results/archival_occupancy_validation_input.csv').open()))
    def group(g):return np.array([float(x['lag_h']) for x in rows if x['group']==g and x['lag_h'].strip()],dtype=float)
    fc1=group('FC1');fc2=group('FC2');tr14=group('Tr14');tr37=group('Tr37')
    assert (len(fc1),len(fc2),len(tr14),len(tr37))==(3,3,1,1)
    diff=fc2-fc1;se=diff.std(ddof=1)/np.sqrt(len(diff));ci=diff.mean()+t.ppf([.025,.975],len(diff)-1)*se
    naive=fc1.mean();t0=fc2.mean();h14=tr14[0];h37=tr37[0]
    advantage0=naive-t0
    ratios={'14h':(naive-h14)/advantage0,'37h':(naive-h37)/advantage0}
    tx=list(csv.DictReader((ROOT/'results/technical_fit_summary.csv').open()))
    d={x['dataset']:x for x in tx}
    worst=[]
    for k in range(1,4):
        a=d[f'FC1-{k}'];b=d[f'FC2-{k}']
        worst.append(float(b['lag_technical_max_h'])-float(a['lag_technical_min_h']))
    result={'unit':'independent flowcell records','FC1_lag_h':fc1.tolist(),'FC2_lag_h':fc2.tolist(),
        'paired_FC2_minus_FC1_h':diff.tolist(),'paired_mean_h':float(diff.mean()),'descriptive_paired_t_95ci_h':ci.tolist(),
        'same_estimator_naive_mean_h':float(naive),'same_estimator_immediate_mean_h':float(t0),
        'same_estimator_14h_single_record_h':float(h14),'same_estimator_37h_single_record_h':float(h37),
        'descriptive_advantage0_h':float(advantage0),'same_estimator_normalized_advantage':ratios,
        '14h_exceeds_immediate':'the descriptive advantage after 14h exceeds the immediate-transfer mean, so these summaries do not follow monotone washout',
        'technical_window_adversarial_paired_difference_h':worst,
        'technical_minima_coincidence':{'FC1-1':{'lag_h':4.9740542653368465,'smoothing_obs':40,'fit_cell_eq':[40,400]},
                                         'FC2-2':{'lag_h':4.972462526416053,'smoothing_obs':20,'fit_cell_eq':[10,250]},
                                         'interpretation':'Different records and different windows, rounded to the same 4.97h; independently recalculated from archived counts and meta files'},
        'biological_interval_for_holding_time_response':'not identifiable from one recording per hold',
        'source_reprocessing':'empirical/extract.py on original Lee et al. binary images, derived counts.csv/metadata released by this research project; not precomputed counts supplied by the original authors'}
    (ROOT/'results/within_estimator_lag_audit.json').write_text(json.dumps(result,indent=2))
    print(json.dumps(result,indent=2))
    return result
if __name__=='__main__':run()
