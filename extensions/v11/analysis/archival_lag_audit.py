"""Independent-unit audit of repository-derived exponential occupancy lags.

These values were generated by the publicly released occupancy.py algorithm,
from GitHub blob sha 97... [see provenance manifest].  The original published
PNAS exponential fit is different and cannot be treated as reproduced by these
numbers.  No biological replication for Tr14/Tr37 is available here.
"""
from pathlib import Path
import argparse, json
import numpy as np
import pandas as pd
from scipy.stats import t

BASE=Path(__file__).resolve().parents[1]

def audit(src):
    d=pd.read_csv(src)
    f1=d[d.group=='FC1'].dropna(subset=['lag_h']).lag_h.to_numpy()
    f2=d[d.group=='FC2'].dropna(subset=['lag_h']).lag_h.to_numpy()
    assert len(f1)==len(f2)==3
    contrast=f2-f1
    mean=float(contrast.mean())
    se=float(contrast.std(ddof=1)/np.sqrt(3))
    ci=(mean-t.ppf(.975,2)*se,mean+t.ppf(.975,2)*se)
    hold=d[d.group.isin(['Tr14','Tr37'])][['group','lag_h']]
    result={
        'source':'Repository occupancy_validation.csv, calculated from image-derived counts; NOT the Lee et al. exponential-fit estimator',
        'FC1_lag_h':f1.tolist(),'FC2_lag_h':f2.tolist(),
        'paired_FC2_minus_FC1_h':contrast.tolist(),'mean_paired_difference_h':mean,
        'descriptive_t95_interval_h':[float(x) for x in ci],
        'n_independent_pairs':3,
        'hold_lag_recomputed_h':dict(zip(hold.group,hold.lag_h)),
        'hold_independent_biological_replicates':{'Tr14':1,'Tr37':1},
        'published_curve_fit_lags_h':{'FC1':17.56,'Tr0':4.68,'Tr14':5.46,'Tr37':13.41},
        'technical_window_sensitivity':'see technical_sensitivity.csv; within-record fitting variation, NOT biological confidence interval',
        'identifiable_between_replicate_washout_CI':False,
    }
    return result

if __name__=='__main__':
    result=audit(BASE/'results/archival_occupancy_validation_input.csv')
    out=BASE/'results/archival_lag_audit_v11.json'
    out.write_text(json.dumps(result,indent=2))
    print(json.dumps(result,indent=2))
